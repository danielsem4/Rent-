import androidx.compose.ui.unit.sp

/**
 * The app-wide type scale, wired into [MaterialTheme.typography]. Uses the platform default font
 * (SF on iOS, Roboto on Android) with a tuned, consistent hierarchy so screens never define their
 * own font sizes. Map by role:
 *
 * - Large screen titles → `displaySmall`, `headlineMedium`
 * - Section titles → `titleLarge`
 * - Card titles → `titleMedium`
 * - Body text → `bodyLarge`, `bodyMedium`
 * - Secondary text → `bodySmall`
 * - Labels / buttons → `labelLarge`, `labelMedium`
 * - Captions → `labelSmall`
 */
